# 汉诺塔的游戏：
def hanoi(n, x, y, z):
    if n == 1:
        print(x, '-->', z)  # 如果只有一层，直接将金片从x移动到z
    else:
        hanoi(n - 1, x, z, y)  # 将x上的金片移动到y
        print(x, '-->', z)  # 将最底下的金片从x移动到z
        hanoi(n - 1, y, x, z)  # 将y上的n-1个金片移动到z


n = int(input('请输入汉诺塔的层数： '))
hanoi(n, "A", "B", "c")
"""
核心思维：宏观视角的“三步走”
这段代码的灵魂在于 else 分支。它没有纠结于“第3个盘子怎么移”、“第5个盘子怎么移”，而是把 n 个盘子的问题，简化成了三个大步骤。
假设我们要把 n 个盘子从 源柱子(x) 移动到 目标柱子(z)，借助 辅助柱子(y)：
第一步（挪开障碍）： 先把最上面的 n-1 个盘子，从 x 移到 y 上。（这样最大的第 n 号盘子就露出来了，且 y 柱子准备好了接它）。
第二步（移动底座）： 把剩下的那个最大的第 n 号盘子，直接从 x 移到 z。
第三步（还原）： 把那 n-1 个盘子，从 y 移到 z 上（盖在最大的盘子上面）。
代码中的参数含义：
hanoi(n, x, y, z) 的意思是：有 n 个盘子，起点是 x，终点是 z，借力的是 y。
(注意：参数顺序很重要，你的代码里 x 是源，z 是目标，y 是辅助)"""


def hanoi(n, x, y, z):
    # n: 盘子数量
    # x: 源柱子 (Start)
    # y: 辅助柱子 (Auxiliary)
    # z: 目标柱子 (Target)

    if n == 1:
        # 【基准情况】
        # 如果只剩 1 个盘子，不需要借助任何人，直接从 x 搬到 z
        print(x, '-->', z)
    else:
        # 【递归步骤】

        # 1. hanoi(n - 1, x, z, y)
        # 目标：把上面的 n-1 个盘子从 x 移到 y。
        # 注意参数变化：起点是 x，目标是 y，所以要借助 z。
        # 这里的逻辑是：“把 z 当作临时中转站，帮我把 n-1 个盘子搬到 y 去”
        hanoi(n - 1, x, z, y)

        # 2. print(x, '-->', z)
        # 此时，x 上只剩最大的盘子，y 上有 n-1 个盘子，z 是空的。
        # 直接把最大的盘子从 x 移到 z。
        print(x, '-->', z)

        # 3. hanoi(n - 1, y, x, z)
        # 目标：把 y 上的 n-1 个盘子移到 z（盖在最大盘子上）。
        # 注意参数变化：起点是 y，目标是 z，所以要借助 x。
        # 这里的逻辑是：“现在 x 是空的，可以当作临时中转站，帮我把 n-1 个盘子从 y 搬到 z”
        hanoi(n - 1, y, x, z)


"""这段代码的精妙之处在于“信任”：
在写 hanoi(n-1, ...) 时，我们不需要去管 n-1 具体是怎么移的，我们只需要假设计算机能完美地把 n-1 个盘子移好，
然后我们只需要负责把最大的那个移过去，剩下的交给递归。
迭代法（你之前的斐波那契）：是一步步算，关注过程。
递归法（汉诺塔）：是层层拆解，关注关系（大问题和小问题的关系）。"""
