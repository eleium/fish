# 对象的魔法方法（magic method）

# 1. __init__(self, ...) 被称作：构造方法或初始化方法
# 作用：在初始化对象的时候，定制个性化的属性

"""
核心功能：
1. 自动调用：当你使用类名加括号实例化对象时（例如 obj = MyClass()），Python 会自动调用 __init__。
2. 属性绑定：它的主要任务是给新创建的对象绑定初始属性（即 self.xxx = value）。
3. 参数传递：它接收你在实例化时传入的参数，并将其保存到对象内部。
"""

# 说明：
# - 在类实例化对象的时候，可以自动调用这个方法。而自己写的个性化的定制，必须手动调用。
# - 可以有或没有参数，没有参数时，实例对象不能传参，只有 (self)。
# - 可以有多个参数
# - 可以直接指定某个参数的值：(self, x, y='hello')

# 对于初学者：
# 区分 __new__ 和 __init__ 会增加学习难度。因为在 99% 的日常开发中，我们只写 __init__，不写 __new__。
# 所以，大家习惯性地把它统称为"构造函数/方法"，意思就是"用来创建对象的那个入口"。

# 对于进阶者：
# 为了体现专业性，会强调它是"初始化方法"，以区别于真正的构造器 __new__。

# 补充说明：
# - 在类的定义内部，它是一个函数；但当它被对象调用时，它就变成了方法。
# - 在 Python 中，"函数"和"方法"的界限其实很模糊，主要取决于它在哪里定义以及如何被调用。
# - 所有的"方法"本质上都是"函数"，但并不是所有的"函数"都能叫"方法"。
#   只有那些"住在类家里"、并且能和对象互动的函数，才有资格被称为"方法"。


# 2. __new__(cls, ...)
# 说明：
# - 事实上，实例化的对象都是用 __new__() 方法创建的。创建后被 __init__() 方法填入具体的属性。
# - Python 的元类才会用到重写 __new__() 方法的情况：在元类中定制类。
#   元类是 Python 难以理解的概念，是魔法方法背后的魔法方法。后面再说。
# - 在继承不可变类型的时候，如果想从中作梗，就可以通过改写 __new__() 方法进行拦截。


class Capstr(str):
    """
    继承自 str 的自定义字符串类
    注意：(str) 并不是在"创建类的时候写入参数"，而是在定义继承关系。
    str 是 Python 内置的字符串类，包含所有字符串的方法，比如 len, upper，子类就可以直接调用。
    """

    def __new__(cls, string):
        # __new__ 发挥作用的地方。因为 str 是不可变类型，一旦创建就不能修改。
        # 如果你想让 CapStr 在创建时就自动变大写，你必须在创建阶段（即 __new__）介入。
        string = string.upper()
        # 调用父类（str）的 __new__ 方法，传入已经变大写的 string，
        # 从而创建一个全新的、内容为大写的字符串对象并返回。
        return super().__new__(cls, string)


cs = Capstr("python")
print(cs)  # ---> PYTHON

# ❌ 错误示例：不应该手动调用魔术方法
# print(cs.__new__())
# 原因：魔术方法应该由 Python 解释器自动触发，手动调用违背设计逻辑。

# 说明：
# 之所以能改变原本不能改变的对象，原因是在对象创建之前就被截断了，截断后改变了。
# 然后才调用 super().__new__()，创建真正的对象。

print(cs.lower())
# 因为 cs 对象属于类 Capstr，而 Capstr 是继承自字符串类 str，
# 所以可以调用字符串类的方法，比如 lower(), len(), upper() 等。

print("-" * 88)

# 3. __del__() 析构方法
# 作用：当对象即将被销毁的时候调用的魔法方法


class C:
    def __init__(self):
        print("我来啦")

    def __del__(self):
        print("我走啦")


c = C()  # ---> 我来啦

# 说明：
# - __init__ 方法会自动调用：当您执行 c = C() 时，Python 会自动调用类 C 的 __init__ 构造方法
# - __init__ 中有 print 语句：在第 63 行，__init__ 方法里有 print("我来啦")
# - 虽然没有显式调用方法，但实例化对象时，__init__ 构造函数会被自动调用，所以会有输出

# ---> 我走啦（在脚本结束时触发）

"""
__del__ 方法的调用时机：
1. 不是实例化时调用：执行 c = C() 时，只会自动调用 __init__，不会调用 __del__。
2. 是对象销毁时调用：__del__ 是析构方法，当对象被垃圾回收器销毁时自动调用。
3. 为什么您会看到"我走啦"：
   - 当 Python 脚本执行完毕，程序即将退出时
   - Python 的垃圾回收机制会清理所有还在内存中的对象
   - 对象 c 被销毁前，自动调用 __del__ 方法
   - 所以输出"我走啦"
"""

del c
# 说明：
# 此时删除 del c，VS Code 并没有啥反应。因为已经在实例化对象时 c = C()，已经运行完了。
# 这是 VS Code 的运行方式：执行完脚本，把内存清出来，也就自动运行了 del c。

"""
在当前文件里，写不写 del c 主要有两个区别：

1. 看到"我走啦"的时机不同
   - 写了 del c：你会在终端里、就在 del c 这一行的位置，立刻看到"我走啦"。你能明确知道析构方法是在哪里被触发的。
   - 没写 del c：你会在终端输出的最末尾（整个脚本跑完之后）才看到"我走啦"。这是因为 VS Code 运行完整个脚本后，进程退出时才会统一清理所有残留对象。

2. 内存释放的"主动性"不同
   - 写了 del c：是你主动告诉 Python："这个对象我不需要了，现在就把它的内存收回去。"
   - 没写 del c：对象会一直留在内存里，直到脚本结束。如果你的脚本非常大，或者你创建了很多大对象，不写 del 可能会导致内存占用过高。
"""

print("*" * 88)

c = C()
# 这时候运行脚本，终端就会出现 我来啦 我走啦
d = c
del c
# 不会出现 我走啦（因为还有 d 引用着对象）
del d
# 此时才会出现 我走啦，因为所有的对象引用都被清理完了。

# 补充：
# __del__() 方法可以创建一个该对象的新引用来推迟这个对象的销毁：对象的重生
# 官方不建议，但是可以实现


# 方法 1：用全局变量的方法实现
class D:
    def __init__(self, name):
        self.name = name

    def __del__(self):
        # 不能用 return 语句，因为销毁是 del 加上对象名。
        # 没有办法在销毁这个对象的同时又把它的返回值给另外一个变量去储存。
        # 所以通过 return 返回值把 self 送出去的方法不通。可以用全局变量。
        # 因为魔法方法其实也是函数。
        global x
        x = self  # 创建一个全局变量，将 self 保存起来


d = D("小甲鱼")
print(d)  # ---> <__main__.D object at 0x...>
print(d.name)  # 小甲鱼
# 以上都很正常，可以显示 d 实例化对象的内存地址，也能访问 d.name 的属性

del d
# 删除 d
print(
    x
)  # ---> <__main__.D object at 0x...>  x 的内存地址跟 d 是一样的，因为全局变量把 self 已经传出去了，给了 x。
print(x.name)  # 小甲鱼

# 注意：非不得已，不要用全局变量，因为它会污染命名空间

# 方法 2：在对象被销毁前，让它调用函数，用参数传递的方式把 self 传出去
# 用函数调用的方式，将这个对象（self）保存起来


class E:
    def __init__(self, name, func):
        self.name = name
        self.func = func

    def __del__(self):
        self.func(self)  # 调用传入的函数，将 self 传递出去


# 说明：
# - 局部变量，使用后就会消失。self 传进来后就是局部变量。
# - Python 的闭包，会将外层函数的局部变量保存下来。

print("-0-" * 40)


# 定义一个闭包函数：
def outter():
    x = 0

    def inner(y=None):
        nonlocal x
        if y:
            x = y
        else:
            return x

    return inner


f = outter()
e = E("小甲鱼", f)
print(e)  # ---> <__main__.E object at 0x...>
print(e.name)  # 小甲鱼

del e
# print(e)  # ❌ 报错：NameError: name 'e' is not defined

g = f()
print(g)  # <__main__.E object at 0x...>  与 print(e) 一样
print(g.name)  # 小甲鱼

# 原理说明：
# 用闭包函数，把 self 保存在外部函数的 x 变量中，而内部函数的作用是窃取这个 self 对象。
# 在 __del__() 魔法方法中，调用它的时候是带有参数的，它就把这个参数储存起来。
# 如果在外边调用这个函数，它不带参数，比如：g = f()，就是用默认值 None，它就会返回刚刚拿到的 self 对象。
# 这就是整个过程。
