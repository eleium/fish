#魔术方法：__index__()
# __index__() 是什么？
# __index__() 是一个魔术方法，用于将对象转换为整数索引。
# 当 Python 需要一个整数索引时（如列表索引、切片、bin() 等），会自动调用这个对象的 __index__() 方法。

# 核心作用
# 返回一个整数，表示该对象在序列索引场景下应该被当作哪个整数使用。

class C():
    def __index__(self):
        print("被拦截啦")
        return 3
        #返回一个整数

c=C()
print(c.__index__())
#--->3

# print(c[3])
#报错：TypeError: 'C' object is not subscriptable
# 类C is not subscriptable: 意思是这个对象不能被当作一个序列（如列表、元组、字符串）来使用，即不能用方括号 [] 来索引或切片。
#当参数是索引值或参数的时候，才可以调用方法__index__():把实例化对象当作索引值的时候才会发生拦截__index__()方法，即这个方法起作用。
s='python'
print(s[c])
#--->3
#--->h
# c对象被当作s的索引值，引发了c.__index__()，得到3，这个3就是s[3],就是'python'的第三个元素：h.

#它不是因为对象的索引而引发的，而是因为对象c被当作一个索引值，才自动引发的。

print(bin(c))
#因为对象c的值是 3，所以bin(3)得到二进制值：0b11
