# “私有变量”：通过某种手段，使得某个对象的方法和属性不能被外部访问。一种保护机制。
# 这是大多数编程语言的都有的概念。但是，Python是开放的，所以，私有变量在这里加上了双引号。
# python 用name manglin的机制，（名字改编，改写，或名字修饰）.
# python 没有只从一个对象内部访问的"私有变量"


class C:
    def __init__(self, x):
        # 类里面的构造函数，创建、定义的是对象的属性。当创建对象时，会自动传入x值，x就是对象的属性。储存数据。
        self.__x = x
        # 这行代码的作用是将传入的参数 x 的值，赋值给当前实例的私有属性 __x。
        # __x是当前实例化对象的私有属性。
        # 并非真正的私有化。

    def set_x(self, x):
        # 创建对象的方法，用来执行操作。
        # 创建一个set_x方法，用来赋值、发送对象的值给私有变量。
        self.__x = x

    def get_x(self):
        # 定义一个函数，用来获得私有变量的值
        print(self.__x)


c = C(250)
# print(c.__x)
# 报错-->AttributeError: 'C' object has no attribute '__x'
# 因为这是一个私有变量__x，所以对象不能直接传入和获得，要用私有变量设定的接口传入和获得。
print(c.get_x())  # --->250

c.set_x(520)
# 用创建类的时候，设置的set_x()接口传入值。这个值可以随时改变。
print(c.get_x())  # --->520
# 用创建类时候，设置的get_x()接口获得值。
# Python 的私有变量并非真正的私有，只是通过名字修饰增加了访问难度，实际上可以通过 c._C__x 访问到。
print(c.__dict__)
# {'_C__x':520} 用__dict__来看看对象c的属性。表示有一个_C__x的属性，值是520。那么就可以直接访问这个属性：
print(c._C__x)
# -->520  果然，可以用这种方法来访问对象的私有属性。 __x是私有属性。 _C__x是这个类的小c这个对象的私有属性。


# 方法也是同样的道理：
