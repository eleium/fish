# 效率
# 对象的属性都是放到一个字典里面  {'name':'小甲鱼','age':18}


class C:
    def __init__(self, x):
        self.x = x


c = C(100)
print(c.__dict__)
# -->{'x':100}
c.y = 200
# 后期添加属性。体现了对象的动态性，或者说这是类的对象的灵活性。
print(c.__dict__)
# -->{'x':100,'y':200}

# 甚至可以直接在字典里面添加键值对，从而改变（增加）对象的属性：
c.__dict__["z"] = 666

print(c.__dict__)
# -->{'x':100,'y':200,'z':666}

print(c.z)
# -->666

# 为啥字典和集合都能高效的运行呢，那是因为字典和集合用空间换来了时间啊。除了费内存之外，都是优点。如何取舍，看当时的情况。
# 有时候创建一个类的时候，很明确的就是用几个属性和方法，不会再扩展。那么就可以用slots方法，避免利用字典存放在空间上的浪费


class C:
    __slots__ = ["x", "y"]

    # 把对象的属性限制在 就x,y两项里。
    def __init__(self, x):
        self.x = x


c = C(889)
# 创建了一个属性受限制的对象小c:

print(c.x)
# -->889
c.y = 567
print(c.y)
# -->567
# print(c.__dict__)
# --->AttributeError: 'C' object has no attribute '__dict__'. Did you mean: '__dir__'?
# 这个类C没有属性字典。

# c.z=666
