"""
✅ 1. Python 的“私有”不是真正的私有
在 Python 中，使用双下划线 __ 开头的属性或方法（如 __x、__fun)并不是真正意义上的“私有”，而是通过 name mangling（名字修饰） 实现的一种保护机制。

当你定义一个私有属性/方法时,Python 会自动将其改名为 _ClassName__attr。
比如:self.__x → 实际上是 self._C__x
这样做的目的是防止子类意外覆盖父类的私有成员。
"""


