# 想要在类的内部创建一个__slots__不包含的属性，也是不可以的。
class D:
    __slots__ = ["x", "y"]

    def __init__(self, x, y, z):
        self.x = x
        self.y = y
        self.z = z


# d=D(10,20,30)

# --->报错： AttirbuteError: 'D' object has no attribute 'z'

# 因为用了__slots__属性，python 会划出固定的空间给这个类。此时，dict 就不需要了，从而节省了空间

# 继承自父类的__slots__属性，是不会在子类中起作用的。
# python只会关注各个具体的类中定义的__slots__属性


class E(C):
    pass


e = E(101)
# 实例化对象的时候必须填上具体的值
e.x = 101
print(e.x)
# --->101
e.y = 202
print(e.y)
# --->202

e.z = 303
print(e.z)
# --->303
print(e.__slots__)
# -->[]'x','y']  查看对象e的__slots__属性，是继承自类C的。
print(e.__dict__)
# -->{'z':303}
# 查看对象e的属性，有z:303这一项

# python 里 ，继承自父类的__slots__属性在子类中不生效，子类可以继续添加自己的属性。
