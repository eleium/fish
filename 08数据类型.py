"""
数据类型一般分为：整数 integers,用int代表.
浮点数floating point number,用float代表.
复数：complex numbers ,包含一个实部和虚部
"""

print(4324342 / 432)
# ---->10010.050925925925        除法运算。得到是浮点数

print(43223423 % 2)
# ---->1         取模计算（求余数）。其实可以看出是判断奇偶数，1为奇数，0为偶数。

print(4432423 // 43)
# ---->103079       求商，舍弃了小数部分,并且向下取整。

# 正整数整除（直接舍弃小数，和日常认知一致）
print(10 // 3)
# ---->3        10 ÷ 3 ≈ 3.333，舍弃小数，输出：3
print(7 // 2)
# ---->3         7 ÷ 2 = 3.5，舍弃小数，输出：3

# 包含负整数的整除（重点：向下取整，不是简单舍弃小数）
print(10 // -3)
# ---->-4        10 ÷ (-3) ≈ -3.333，向下取整为 -4，输出：-4
print(-10 // 3)
# ---->-4         -10 ÷ 3 ≈ -3.333，向下取整为 -4，输出：-4


a = 433.232
print(type(a))
# ---><class 'float'>

b = 0.1 + 0.3
c = 0.1 + 0.2
print(b, c)
# ---->0.4  0.300000000000000004

i = 0
while i < 1:
    print(i)
    i = i + 0.1

print(0.1 + 0.2 == 0.3)
# ---->False

print("- -" * 40)

import decimal
# 引入 decimal模块 十进制的意思

e = decimal.Decimal(
    0.1
)  # 括号内是数字,浮点数，这时候还是不精确的小数，结果也是小数浮点数。
f = decimal.Decimal(0.2)
print(e + f)
# ---->0.3000000000000000166533453694

e = decimal.Decimal(
    "0.1"
)  # 括号内是字符串，decimal会直接用十进制来计算，结果就是精确的0.3
f = decimal.Decimal("0.2")
print(e + f)
# ---->0.3

# E记法 科学计数法
k = 0.00005
print(k)
# ----->5e-05      5的10的负5次方。

# 复数： complex numbers
x = 1 + 2j
# 1是实部，2j是虚部,都是浮点数来存放
print(x.real)
# ---->1.0    获得实部1.0(浮点数）
print(x.imag)
# ---->2.o    获得虚部2.0（浮点数）
print(x)
# --->(1+2j)
