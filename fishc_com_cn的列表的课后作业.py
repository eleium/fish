# 如何不直接使用下标索引值的前提下，把列表中的'黑寡妇'替换为'神奇女侠'?
heros = ["蜘蛛侠", "绿巨人", "黑寡妇", "鹰眼", "灭霸", "雷神"]

heros.remove("黑寡妇")
heros.insert(2, "神奇女侠")
print(heros)

# 如何将上面列表的'蜘蛛侠'和'绿巨人'替换成'猪猪侠'和'女巨人'?

heros[0:3] = [
    "猪猪侠",
    "女巨人",
]  # 下标索引值范围只有1位，而要加入的元素有两个，就变成增加
# 两个元素，而不是替换。要替换就要把下标范围扩大到要加入的元素数量以上。heros[0:2]
print(heros)
