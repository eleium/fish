#因为 x=520 是写死在 TC/__init__.py 源文件里的。当你运行程序时：
# Python 读取 TC/__init__.py，执行 x = 520。
# 这个 x 作为 TC 包对象的属性，被加载到内存中。
# 你在 tc_test.py 中执行 TC.x = 1000，修改的是内存中的 TC 对象的属性。
# 源文件 TC/__init__.py 本身没有被修改，它的内容还是 x=520。

# 虽然源文件不会被修改，但内存中的包对象被修改了，在当前程序的运行期间，所有导入这个包的地方都会看到修改后的值。


