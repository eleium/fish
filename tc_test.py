import TC

print(f"32摄氏度={TC.tc.c2f(32):.2f}华氏度")
print(f"99华氏度={TC.tc.f2c(99):.2f}摄氏度")
# --->测试，0摄氏度=32.00 华氏度
# --->测试，0华氏度=-17.78 摄氏度
# --->32摄氏度=89.60华氏度
# --->99华氏度=37.22摄氏度

# 模块被导入后，会从头到尾完全执行一遍的。
# 模块tc.py本身就有两行测试语句，加上主文件的两行print语句，所以打印了4行结果。


# 解决办法： 在模块里添加 if __name__='__main__' .当一个模块作为脚本，独立执行的时候，它的__name__属性就会被赋值为'__main__'
# 因此，只要在模块执行前判断__name__是否等于'__main__',就可以解决问题。
# 核心原因：__name__ 的值在“被导入”和“作为主程序运行”时是不一样的。

# 一、__name__ 的两个值
# 执行方式	                          __name__ 的值	                 说明
# 作为主程序运行（直接运行这个文件）	'__main__'	                   Python 把正在运行的文件命名为 __main__
# 被导入为模块（import tc）	          'tc'（模块名）	              Python 把模块的名字赋值给 __name__

# 这个机制的作用是：让一个文件既可以当作独立脚本运行（做测试），又可以当作模块被其他文件导入使用（不执行测试代码）。
# if __name__ == '__main__': 的原理是：
# 文件直接运行时，__name__ 是 '__main__'；tc.py直接运行，执行两个print()语句。
# 被导入时，__name__ 是模块名 'tc'。  tc.py被导入，就不执行自己的那两个print()语句。
# 所以通过判断 __name__ 的值，就能区分“当前文件是被运行还是被导入”，从而控制哪些代码只在直接运行时执行。


# if __name__=='__main__':  它必须在要执行的代码之前。因为 Python 是逐行执行的，如果 if 语句出现在调用函数之后，而函数还没定义，就会报错
# 它是个判断语句，要保持正确的缩进。


# --->__name__的值是tc  由于导入tc.py,所以不执行tc.py的两个print()语句
# --->32摄氏度=89.60华氏度
# --->99华氏度=37.22摄氏度


