# 字符串的格式化 format方法， f方法：f-string格式化字符串

year=2010
# '山姆店成立于 year 年'
print('山姆店成立于 {} 年'.format(year))
print('hello world'.partition('.'))#partion()方法：三分法：将字符串以指定的字符分割成三个部分。
#format方法：字符串的格式化方法，可以使用{}占位符来表示需要替换的值，然后通过format()方法传入对应的值进行替换。
print('1+2={},2的平方是{},3的立方是{}'.format(1+2,2*2,3*3*3))

print("{}看到{}就很激动".format('小王', '小明'))
print("{1}看到{0}就很激动".format('小王', '小明'))#添加索引来指定参数的位置。
print('{0}{0}{1}{1}'.format('好', '中'))#参数可多次引用
print('我叫{name},我爱{omg}'.format(name='小王', omg='python'))#使用关键字参数。

'''
{name} 和 {omg} 是字符串中的占位符（使用花括号包围）
name='小王' 和 omg='python' 是传递给 format() 方法的关键字参数
name 和 omg 是参数的名字（关键字）
'小王' 和 'python' 是对应的参数值
'''
#位置参数与关键字参数混合使用：关键参数不能放到位置参数的前面。
print('我叫{name},我爱{0}，我还喜欢{1},喜欢{1}的人运气好'.format( 'python', 'pycharm',name='小明'))

print('{},{},{}'.format(1, {}, 3))
print('{},{{}},{}'.format(1, 3))
#以上输出结果为：1,{},3，都可以输出{}，但是{}不能输出{}，因为{}是字符串中的占位符，不能被{}所替换。


#排列：居中排列：{1 ：^ width},width表示在 width宽度内.居中：^,左对齐：<,右对齐:<。 1 是索引。
print('{:^10}'.format(250))

print('{1:>10},{0:<20}'.format(340, 520))
#索引0-->340,<20左对齐，占用20个字符宽度，结果："340                 "（"340" + 后面 17 个空格），左对齐参数在最左侧。
# 索引1-->520,>10右对齐，占用10个字符宽度，结果："       520"（前面 7 个空格 + "520"）。右对齐参数在最右侧
# 最终结果："       520,340                 "。

print('{left:>10},{right:<20}'.format(left='hello', right='world'))#关键字参数同样可以排列。
print('{left:>10},{right:>20}'.format(left='hello', right='world'))#关键字参数同样可以排列。

print('{:020}'.format(-300))#20个字符宽度，感知参数负数。---->-0000000000000000300.只对数字，非数字无效。
print('{1:%^10}{0:@^20}'.format(340, 520))#可以用指定的字符填充。
print('{:0=10}'.format(520))

""""
0=10 是一个特殊的格式化用法，专门用于数字格式化！
0 :填充字符（用 0 填充）
= : 对齐方式（符号对齐，sign-aware padding）
10 : 总宽度为 10 个字符

对齐的特殊之处：
是数字专用的对齐方式，它会让：
符号（+/-） 保持在最左边
填充字符 放在符号和数字之间
数字 靠右对齐
总结：0=10 是数字格式化的专业写法，确保符号始终在最左边，数字用 0 填充到指定宽度！
"""