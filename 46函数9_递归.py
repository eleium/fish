# 用递归函数来实现取得一个整数的阶乘：定义一个函数，它的参数就是要每次运算的数值。并且数值每次减一。当检测到参数为1的时候就停止调用。
def factrecur(n):
    if n == 1:
        return 1
    else:
        return n * factrecur(n - 1)
    # 递归函数：调用自己，并且每次参数减一


result = factrecur(5)
print(result)  # --->120


# 用迭代和递归的方式实现斐波那契数列：这个函数用迭代法计算斐波那契数列第n项。
def fibIter(n):  # 定义一个斐波那契函数，用迭代的方法(iter)
    a = 1  # 初始化：F(1) = 1
    b = 1  # 初始化：F(2) = 1
    c = 1  # 默认返回值（处理n=1或n=2的情况）
    while n > 2:  # 当n>2时才需要计算，F(1)和F(2)直接返回1
        c = a + b  # 核心：当前项 = 前两项之和
        a = b  # 窗口右移：a变成原来的b（前第二项）
        b = c  # 窗口右移：b变成刚算出的c（前第一项）
        n -= 1  # 计数器减1，控制循环次数
    return c  # 返回第n项的值


result_iter = fibIter(20)
print(result_iter)  # --->6765  求的是斐波那契第20项的值。
# 倒着计算：从20开始，-->19-->18,每次减1，直到1或2。
"""核心逻辑
滑动窗口思想：a和b始终保存"前两项"，每次计算出新的一项c后，窗口向右滑动
循环次数：n=3时循环1次，n=4时循环2次，n=k时循环(k-2)次
时间复杂度O(n)，比递归的O(2ⁿ)高效得多
"""


# 用递归的方式实现求斐波那契数列的第n项：
def fibRecur(n):
    if n == 1 or n == 2:
        return 1
    else:
        return fibRecur(n - 1) + fibRecur(n - 2)


result_recure = fibRecur(20)
print(result_recure)  # --->6765
# 斐波那契数列定义
# F(n) = F(n-1) + F(n-2)，前两项都是1：
# F(1)=1, F(2)=1, F(3)=2, F(4)=3, F(5)=5, ...


# 斐波那契 = "当前项依赖前两项"
# → 递归：直接表达依赖关系
# → 迭代：从小到大逐步构建


