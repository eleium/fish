# 用迭代和递归两种方法，实现一个整数的阶乘：阶乘就是所有小于等于本整数的乘积 。比如：5的阶乘是5*4*3*2*1=120
def factiter(n):
    result = n
    for i in range(1, n):
        result *= i
    return result


num = factiter(5)
print(num)
