# 字典的6中创建方法：
a = {'a': 1, 'b': 2}  # 直接赋值变量名，用大括号，里面键值对，冒号，就是字典。

# b=dict('雷锋'='好人') 中文不能直接=赋值
'''
错误原因：dict(键=值) 这种语法要求"键"必须是合法的 Python 标识符（英文字母、数字、下划线组成，不能以数字开头）
中文字符串作为键：必须使用 dict([('键', '值')]) 或直接用 {} 的方式
推荐：对于中文键，直接使用 {'雷锋': '好人'} 最清晰明了'''

b = dict([('雷锋', '好人'), ('黄继光', '英雄')])  # 用列表的方法： dict([('键', '值')]):列表中的元素是每个用括号括起来的键值对.
c = dict(雷锋='好人')  # 雷锋不加引号，直接赋值。key 中文不能加引号
print(type(b))  # ---><class 'dict'>
d = dict(zip(['关羽', '张飞', '刘备'], ['云长', '翼德', '玄德']))  # 用zip()聚合迭代器的方法
e = dict({'吕布': '奉先', '赵云': '子龙', '周瑜': '公瑾'}, 曹操='孟德')  # 追加额外键值对成为新字典
print(e)
f = dict({'关羽': '云长', '张飞': '翼德', '刘备': '玄德'})  # 复制字典：通过dict()构造函数，复制已有字典。
"""
总结 6 种创建方法：
1,直接字面量：a = {'a': 1, 'b': 2}
2,元组列表：b = dict([('雷锋', '好人'), ('黄继光', '英雄')])
3,关键字参数：c = dict(雷锋='好人')（键必须是合法标识符:中文不能有引号）
4,zip() 聚合：d = dict(zip(['关羽','张飞'], ['云长','翼德']))
5,字典+额外键值对：e = dict({'吕布':'奉先'}, 曹操='孟德')
6,复制字典：f = dict({'关羽':'云长','张飞':'翼德'}) ← 这就是第 6 种
不过严格来说，第 6 种和第 1 种本质相同，只是多套了一层 dict() 构造函数。实际开发中更常用的是 .copy() 方法来复制字典。
"""

# 字典的增删改查：fromkeys()方法
d = {'关羽': '云长', '张飞': '翼德', '刘备': '玄德'}
print(dict.fromkeys(d, 250))  # --->{'关羽':250,'张飞':250,'刘备':250} 更改原value.

m = dict.fromkeys('china', 300)
print(
    m
)  # -->{'c':300,'h'：300，'i':300,'n':300,'a':300} 赋给可迭代对象china键值，并新创一个字典。
m['c'] = 20
print(m)  # -->{'c':20,'h':300,'i':300,'n':300,'a':300} 更改字典里的某一个键值对的值。
m['e'] = 390
print(m)  # --->{'c':20,'h':300,'i':300,'n':300,'a':300,'e':390} 添加键值对。

# 字典没有重复的键值对。

# 删除字典中指定的元素:pop()方法
d = {'关羽': '云长', '张飞': '翼德', '刘备': '玄德'}
d.pop('关羽')
print(d)  # -->{'张飞':'翼德':'刘备':'玄德'}#用pop()方法删除了字典中指定的元素。

# d.pop('赵云')#j将抛出异常，因为'赵云'并非原字典的项。
print(d.pop('赵云', '赵云不存在'))  # -->赵云不存在。用pop(不存在的key,显示内容）删除不存在的键值对，返回显示内容。

# 跟pop()方法类似的还有一个： popitem()方法。python3.7之前，随机删除一个键值对。python3.7之后，删除字典中最后一个键值对。

print(d.popitem())  # -->('刘备','玄德')为啥是元组？由于需要同时返回 key 和 value 两个值，Python 选择用元组来打包这两个值。
print(d)  # -->{'关羽':'云长','张飞':'翼德'}

# del()语句:删除指定的键值对。del是类似与if , for ,while 等等的关键字，是语句，不是方法。
# d.del('关羽')
del d['张飞']
print(d)
"""
del 是语句，不是方法
关键区别：
del 是 Python 的关键字（keyword），是一条删除语句
它不是字典对象的方法
它是 Python 语言的内置语法结构
类似于 if、for、while、return 等关键字

方法是对象的属性，需要通过 . 调用
例如：d.pop()、d.keys()、d.get() 这些才是字典的方法
方法定义在类的内部，属于对象

del 可以删除各种东西，不仅限于字典
del 语句：更通用，可以删除任何对象、变量、元素等
pop() 方法：专门用于字典/列表，删除的同时还能返回被删除的值
总结：del 是 Python 的关键字（语句），不是字典的方法，所以不能用 d.del() 的格式。
如果想用方法的形式删除字典元素，应该使用 d.pop(key)。
"""

