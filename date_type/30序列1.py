# print(x,y)
#报错：NameError: name 'x' is not defined。删除的非常干净。



x=[1,2,3,4,5]
print(id(x))
del(x[1:4])
print(x)#---->[1,5],切片语法也可以达到同样的效果。



y=[1,2,3,4,5]
print(id(y))
y[1:4]=[]#空[]的作用步骤：1先清空1-4（不含4）的元素；2，在空[]中插入剩余元素。
print(y)#---->[1,5]

print(id(x))
print(id(y))
#x,y的id没有改变，why?
"""
del(x[1:4]) 是原地修改列表对象
它直接修改了列表的内容，但列表对象本身在内存中的位置没有改变
就像你有一个盒子（列表），你从盒子里拿出一些东西（删除元素），但盒子本身还是那个盒子
元组是不可变序列，每次修改操作都会创建新的元组对象,所以 ID 会改变。所以叫 不可变 。

核心原理：可变序列（列表）支持原地修改操作，这些操作不会创建新对象，因此 id() 保持不变。这正是 Python 内存优化的体现！
"""

x=[1,2,3,4,5]
del x[::2]#删除列表中每隔一个元素.默认从0开始，步长为2。
print(x)#---->[2,4]

y=[1,2,3,4,5]
# y[::2]=[]
print(y)#报错：不能用切片的方法赋值给空列表。
"""
带步长 ::2 的切片，Python 强制要求：
左边长度 = 右边长度
你左边要替换 3 个位置右边却只给了 0 个元素→ 长度不匹配 → 报错！

普通切片 y[a:b]
→ 可以赋值任意长度列表，包括 []
带步长切片 y[::n]
→ 必须赋值长度相同的列表
→ 不能用 [] 清空！

切片没步长 → 随便赋值
切片有步长 → 长度必须一样
想直接删除 → 用 del
"""
print('-'*50)

x=[1,2,3,4,5]
x.clear()
print(x)#---->[]
del x[:]
print(x)#---->[]清空列表但是保留一个空列表。而不是del x ,直接删除了x.