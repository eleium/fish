"""
列表、元组、字符串有很多相同相似的点：
1.都可以通过索引获取元素
2.第一个元素的索引值都是 0
3.都可以用切片的方法来获取一个范围内的元素的集合
4.都有很多共同的运算符

python 将列表list 元组tuple 字符串string 都作为序列。序列又分为：可变序列和不可变序列。比如：列表 可变。 元组与字符串不可变。

"""
# 能够作用与序列的运算符和函数： +  和 * 。+：拼接; *: 重复
print([1, 2, 3] + [4, 5, 6])  # ---->[1, 2, 3, 4, 5, 6]列表拼接后还是列表
print((1, 2, 3) + (4, 5, 6))  # ---->(1,2,3,4,5,6)元组拼接后还是元组
print('hello' + 'world')  # ---->'helloworld'字符串拼接后还是字符串
print('123' + '456')  # ---->'123456' print函数会自动去掉字符串的引号---->123456
""""
✅ '123' + '456' 返回的是字符串 '123456'（内存中带引号）
✅ print() 输出时显示为 123456（屏幕上不带引号）
✅ 你的注释 # ---->'123456' 应该改成 # ----> 123456 更准确
这就是为什么你的注释写 '123456' 看起来不对，因为实际输出没有引号！
"""

print([1, 2, 3] * 3)  # ---->[1, 2, 3, 1, 2, 3, 1, 2, 3]
print((1, 2, 3) * 3)  # ---->(1,2,3,1,2,3,1,2,3)
print('hello' * 3)  # ---->'hellohellohello'
print('123' * 3)  # ---->123123123内存里带引号，print输出时去掉了引号.

s = [1, 2, 3]
print(id(s))  # 列表在内存中的位置

# 增量赋值：
# print(s *= 2)#报错：赋值运算符（=, *=, +=, -= 等）不能放在函数调用里！
s*=2
print(s)#---->[1,2,3,1,2,3] 等于 print(s*2)
print(id(s))#列表在内存中的位置没有改变.

"""
在python 中，每一个对象有三个基本属性：
第一个：唯一标志 创建时就有的，不可改变，不可重复。id:代表返回一个指定对象的唯一标志的整数值
第二个：类型
第三个：值
"""
print('-'*50)
#以上id位置不变是针对可变序列，那么对于不可变序列呢？比如元组:
