a = ["张", "王", "李", "赵"]
a[3] = "钱"
print(a)
# --->['张','王','李','钱']

# 我们知道，列表的 index() 方法可以找到第一个匹配元素的下标，
# 在不改变原列表的情况下，找到最后一个匹配元素的下标呢？（有两种方法可以实现）
print(a[-1])

num = len(a)
print(a[num - 1])

a = ["张", "王", "李", "赵", "李", "钱"]

target = "李"
# 从列表末尾倒着循环（索引从大到小）
for i in range(len(a) - 1, -1, -1):
    if a[i] == target:
        print(f"最后一个 '{target}' 的下标是: {i}")
        break  # 找到第一个（倒着数的第一个）就停
